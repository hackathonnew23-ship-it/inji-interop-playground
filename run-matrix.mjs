// Headless run of the playground's real protocol code (same functions as index.html).
// Usage: node scripts/run-matrix.mjs   -> writes docs/test-results/*.json and results.md
import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const start = html.indexOf('// ---------- helpers'), end = html.indexOf('// ---------- UI');
const code = html.slice(start, end).replace(/const \$=s=>document\.querySelector\(s\), /, 'const ');
const rnd = () => Math.random().toString(36).slice(2, 10);
const api = new Function(code + '; return {ISS,WAL,VER,SCN,initKeys,issueCore,verifyCore};')();
await api.initKeys();
const { ISS, WAL, VER, SCN, issueCore, verifyCore } = api;
const all = {}, rows = [];
for (const fmt of ['sd-jwt', 'ldp_vc']) for (const sc of Object.keys(SCN)) {
  const cells = {};
  for (const i in ISS) for (const w in WAL) for (const v in VER) {
    const r = await issueCore(i, w, fmt, { type: 'University ID', name: 'Test Holder', number: 'T-001', detail: 'Demo' });
    let T = r.T, pass = false, label = 'FAIL', reason = r.ok ? '' : r.T.at(-1).d;
    if (r.ok) {
      const x = await verifyCore(v, r.cred, rnd(), sc, null);
      T = r.T.concat(x.checks); const bad = x.checks.find(c => !c.ok);
      if (sc === 'none') { pass = x.ok; label = pass ? 'PASS' : 'FAIL'; reason = bad ? bad.d : ''; }
      else { pass = !x.ok && bad.t !== 'Format supported'; label = pass ? 'REJECTED' : 'FAIL'; reason = bad ? bad.t + ': ' + bad.d : ''; }
    }
    cells[`${ISS[i].name} > ${WAL[w].name} > ${VER[v].name}`] = { pass, label, reason, steps: T };
    rows.push({ fmt, scenario: SCN[sc], path: `${ISS[i].name} > ${WAL[w].name} > ${VER[v].name}`, label, reason });
  }
  all[`${fmt}__${sc}`] = cells;
}
writeFileSync(new URL('../docs/test-results/interop-report.json', import.meta.url), JSON.stringify({ generated: new Date().toISOString(), results: all }, null, 2));
const tot = rows.length, ok = rows.filter(r => r.label !== 'FAIL').length;
let md = `# Test results\n\nGenerated by \`node scripts/run-matrix.mjs\` using the same protocol code as the website.\n\n**${tot} runs: ${ok} behaved as expected, ${tot - ok} failed because of a real format mismatch.**\n\nPASS = flow works. REJECTED = attack correctly caught. FAIL = pairing does not interoperate (reason shown).\n\n`;
for (const fmt of ['sd-jwt', 'ldp_vc']) for (const sc of Object.keys(SCN)) {
  md += `\n## ${fmt}, ${SCN[sc]}\n\n| Issuer > Wallet > Verifier | Result | Detail |\n|---|---|---|\n`;
  rows.filter(r => r.fmt === fmt && r.scenario === SCN[sc]).forEach(r => md += `| ${r.path} | ${r.label} | ${r.reason.replace(/\|/g, '/')} |\n`);
}
writeFileSync(new URL('../docs/test-results/results.md', import.meta.url), md);
console.log(tot + ' runs,', ok, 'as expected,', tot - ok, 'format FAIL');
